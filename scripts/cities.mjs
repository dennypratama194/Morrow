// Builds src/lib/cities.ts: every IANA zone's main city (with the coordinates and country from tzdata's zone.tab),
// plus big cities that share a zone with another city's name. Run: node scripts/cities.mjs [/usr/share/zoneinfo]
import { readFileSync, writeFileSync } from 'node:fs';

const dir = process.argv[2] ?? '/usr/share/zoneinfo';
const countries = Object.fromEntries(
  readFileSync(`${dir}/iso3166.tab`, 'utf8').split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.split('\t')),
);
// tzdata's own spellings, swapped for the ones people use
Object.assign(countries, { GB: 'United Kingdom', US: 'United States', KR: 'South Korea', RU: 'Russia', VN: 'Vietnam' });
const known = new Set(Intl.supportedValuesOf('timeZone'));
const dms = (s, deg) => {
  const sign = s[0] === '-' ? -1 : 1;
  const d = +s.slice(1, 1 + deg);
  const m = +s.slice(1 + deg, 3 + deg);
  const sec = +(s.slice(3 + deg, 5 + deg) || 0);
  return Math.round(sign * (d + m / 60 + sec / 3600) * 10) / 10;
};

const rows = [];
for (const line of readFileSync(`${dir}/zone.tab`, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [cc, coord, tz] = line.split('\t');
  if (!known.has(tz)) continue;
  const [, la, lo] = coord.match(/^([+-]\d+)([+-]\d+)$/);
  const name = tz.split('/').pop().replace(/_/g, ' ');
  rows.push([name, tz, dms(la, 2), dms(lo, 3), countries[cc] ?? cc]);
}

